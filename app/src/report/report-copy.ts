export const reportTextZh = (value: string | null | undefined): string => {
  if (!value) return "待研究确认";
  const exact = zhByOriginal[value];
  if (exact) return exact;
  return Object.entries(zhByOriginal).reduce(
    (text, [original, translated]) => text.includes(original) ? text.replaceAll(original, translated) : text,
    value,
  )
    .replaceAll("。；", "；")
    .replaceAll("Claim", "宣传声明")
    .replace(/([。；，：！？])\s+(?=[\u3400-\u9fff])/gu, "$1")
    .replace(/是\s+(?=[\u3400-\u9fff])/gu, "是");
};

/** Merge overlapping execution requirements and decision gates into one reader-facing checklist. */
export const mergedNextStageChecklistZh = (
  requirements: readonly string[],
  entryConditions: readonly string[],
): string[] => {
  const items = [...requirements, ...entryConditions].map(reportTextZh);
  const groups: Array<{ pattern: RegExp; text: string }> = [
    {
      pattern: /候选样品编号|最终目标款|目标款规格/u,
      text: "确定最终要测试的目标款，并确认成分、克重、弹力、尺码和工艺规格。",
    },
    {
      pattern: /用户证据|需求证据|反向反馈|独立来源/u,
      text: "补充更多渠道的用户反馈和反向证据，至少覆盖一个独立来源平台。",
    },
    {
      pattern: /供应商|正式报价|物流核算|MOQ|样品费|交期|包装尺寸|包装重量|产品净重/u,
      text: "取得可比较的正式供应商规格、报价、MOQ、交期和物流核算资料。",
    },
    {
      pattern: /样品|实测/u,
      text: "经人工确认后，完成目标样品的小规模实测。",
    },
    {
      pattern: /合规|标签|医疗|身体改变宣传/u,
      text: "补齐适用的产品标签、宣传声明与合规材料。",
    },
    {
      pattern: /单位经济|单件成本|毛利|履约/u,
      text: "算清单件成本、毛利和履约费用；未知项保持未知，不填 0。",
    },
    {
      pattern: /风险、上架和广告测试门槛/u,
      text: "在正式上架或投放前，通过风险、上架和广告测试的全部门槛。",
    },
  ];
  const categorized = new Set<number>();
  const checklist = groups.flatMap((group) => {
    const matching = items
      .map((item, index) => ({ item, index }))
      .filter(({ item, index }) => !categorized.has(index) && group.pattern.test(item));
    matching.forEach(({ index }) => categorized.add(index));
    return matching.length > 0 ? [group.text] : [];
  });
  const remaining = items.filter((_, index) => !categorized.has(index));
  return [...new Set([...checklist, ...remaining])];
};

